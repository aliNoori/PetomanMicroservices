import {
  HttpException,
  HttpStatus,
} from '@nestjs/common';

import {
  ERROR_CODES,
  ErrorCode,
} from '../constants/error-code.constants';

import {
  ERROR_HTTP_STATUS,
} from '../constants/error-status.constants';

export interface MappedError {
  readonly code: string;
  readonly message?: string;
  readonly status: HttpStatus;
  readonly hasOriginalMessage: boolean;
  readonly isDownstreamError: boolean;
  readonly response?: unknown;
}

interface ErrorResponseObject {
  success?: unknown;
  error?: unknown;
  meta?: unknown;
  code?: unknown;
  message?: unknown;
}

export class ErrorMapper {
  static map(exception: unknown): MappedError {
    // ============================================================
    // HttpException
    // ============================================================

    if (exception instanceof HttpException) {
      const status =
        exception.getStatus();

      const response =
        exception.getResponse();

      // ==========================================================
      // Downstream envelope
      //
      // Example:
      //
      // {
      //   success: false,
      //   error: {
      //     code: 'AUTH_TENANT_MEMBERSHIP_INVALID_STATUS',
      //     message: 'Only pending membership requests can be rejected.'
      //   },
      //   meta: {
      //     requestId: '...',
      //     timestamp: '...'
      //   }
      // }
      //
      // IMPORTANT:
      //
      // Gateway MUST NOT map or translate this response.
      // ==========================================================

      if (
        this.isDownstreamErrorResponse(response)
      ) {
        const error =
          response.error as Record<string, unknown>;

        const code =
          typeof error.code === 'string'
            ? error.code
            : 'DOWNSTREAM_ERROR';

        const message =
          typeof error.message === 'string'
            ? error.message
            : undefined;

        return {
          code,
          message,
          status: status as HttpStatus,
          hasOriginalMessage:
            typeof message === 'string',
          isDownstreamError: true,
          response,
        };
      }

      // ==========================================================
      // Simple structured HttpException
      //
      // Used for errors generated by Gateway itself.
      // ==========================================================

      if (
        this.isSimpleErrorResponse(response)
      ) {
        const code =
          typeof response.code === 'string'
            ? response.code
            : undefined;

        const message =
          typeof response.message === 'string'
            ? response.message
            : undefined;

        if (code) {
          return {
            code,
            message,
            status: status as HttpStatus,
            hasOriginalMessage:
              typeof message === 'string',
            isDownstreamError: false,
          };
        }
      }

      // ==========================================================
      // NestJS string response
      // ==========================================================

      if (typeof response === 'string') {
        return {
          code:
            this.resolveStatusCode(status),
          message: response,
          status:
            status as HttpStatus,
          hasOriginalMessage: true,
          isDownstreamError: false,
        };
      }

      // ==========================================================
      // HttpException without structured code
      // ==========================================================

      return {
        code:
          this.resolveStatusCode(status),
        status:
          status as HttpStatus,
        hasOriginalMessage: false,
        isDownstreamError: false,
      };
    }

    // ============================================================
    // Unknown / unexpected error
    // ============================================================

    return {
      code:
        ERROR_CODES.INTERNAL_SERVER_ERROR,

      status:
        ERROR_HTTP_STATUS[
          ERROR_CODES.INTERNAL_SERVER_ERROR
        ],

      hasOriginalMessage: false,

      isDownstreamError: false,
    };
  }

  // ============================================================
  // Downstream Error Detection
  // ============================================================

  private static isDownstreamErrorResponse(
    response: unknown,
  ): response is ErrorResponseObject {
    if (
      typeof response !== 'object' ||
      response === null
    ) {
      return false;
    }

    if (
      !('success' in response) ||
      !('error' in response)
    ) {
      return false;
    }

    const success =
      response.success;

    const error =
      response.error;

    if (success !== false) {
      return false;
    }

    if (
      typeof error !== 'object' ||
      error === null
    ) {
      return false;
    }

    return (
      'code' in error &&
      typeof error.code === 'string'
    );
  }

  // ============================================================
  // Simple Gateway Error Detection
  // ============================================================

  private static isSimpleErrorResponse(
    response: unknown,
  ): response is {
    code?: unknown;
    message?: unknown;
  } {
    return (
      typeof response === 'object' &&
      response !== null
    );
  }

  // ============================================================
  // HTTP Status -> Gateway Error Code
  //
  // ONLY used for errors generated by Gateway itself.
  // ============================================================

  private static resolveStatusCode(
    status: number,
  ): ErrorCode {
    switch (status) {
      case HttpStatus.BAD_REQUEST:
        return ERROR_CODES.BAD_REQUEST;

      case HttpStatus.UNAUTHORIZED:
        return ERROR_CODES.AUTH_UNAUTHORIZED;

      case HttpStatus.FORBIDDEN:
        return ERROR_CODES.AUTH_FORBIDDEN;

      case HttpStatus.NOT_FOUND:
        return ERROR_CODES.NOT_FOUND;

      case HttpStatus.CONFLICT:
        return ERROR_CODES.CONFLICT;

      case HttpStatus.UNPROCESSABLE_ENTITY:
        return ERROR_CODES.VALIDATION_ERROR;

      case HttpStatus.SERVICE_UNAVAILABLE:
        return ERROR_CODES.SERVICE_UNAVAILABLE;

      case HttpStatus.GATEWAY_TIMEOUT:
        return ERROR_CODES.SERVICE_TIMEOUT;

      default:
        return ERROR_CODES.INTERNAL_SERVER_ERROR;
    }
  }
}
