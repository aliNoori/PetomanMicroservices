import { ArgumentsHost, Catch, ExceptionFilter } from '@nestjs/common';

import { Request, Response } from 'express';

import { RequestWithId } from '../middleware/request-id.middleware';

import { ApiErrorResponse } from '../types/api-response.type';

import { ErrorMapper } from '../utils/error-mapper';

interface DownstreamErrorEnvelope {
  success: false;
  error: {
    code: string;
    message: string;
  };
  meta?: {
    requestId?: string;
    timestamp?: string;
    [key: string]: unknown;
  };
}

@Catch()
export class GlobalExceptionFilter implements ExceptionFilter {
  catch(exception: unknown, host: ArgumentsHost): void {
    const context = host.switchToHttp();

    const request = context.getRequest<RequestWithId>();

    const response = context.getResponse<Response>();

    // ============================================================
    // Map exception
    // ============================================================

    const mappedError = ErrorMapper.map(exception);

    // ============================================================
    // DOWNSTREAM RESPONSE
    //
    // Auth / Market / Vet / Pharmacy already created
    // the complete API response.
    //
    // Gateway MUST NOT:
    //
    // - translate
    // - remap code
    // - replace message
    // - create a new envelope
    //
    // It simply forwards the response.
    // ============================================================

    if (mappedError.isDownstreamError) {
      if (this.isDownstreamEnvelope(mappedError.response)) {
        response.status(mappedError.status).json(mappedError.response);

        return;
      }

      response.status(mappedError.status).json({
        success: false,
        error: {
          code: mappedError.code,
          message:
            mappedError.message ?? 'The downstream service returned an error.',
        },
        meta: {
          requestId: request.requestId,
          timestamp: new Date().toISOString(),
        },
      });

      return;
    }

    // ============================================================
    // GATEWAY-OWN ERROR
    //
    // Only errors generated by Gateway itself come here.
    // ============================================================

    const errorResponse: ApiErrorResponse = {
      success: false,

      error: {
        code: mappedError.code,

        message:
          mappedError.message ?? this.getDefaultMessage(mappedError.code),
      },

      meta: {
        requestId: request.requestId,

        timestamp: new Date().toISOString(),
      },
    };

    response.status(mappedError.status).json(errorResponse);
  }

  // ============================================================
  // Downstream Envelope Validation
  // ============================================================

  private isDownstreamEnvelope(
    value: unknown,
  ): value is DownstreamErrorEnvelope {
    if (typeof value !== 'object' || value === null) {
      return false;
    }

    if (!('success' in value) || !('error' in value)) {
      return false;
    }

    const response = value as Record<string, unknown>;

    if (response.success !== false) {
      return false;
    }

    const error = response.error;

    if (typeof error !== 'object' || error === null) {
      return false;
    }

    const errorObject = error as Record<string, unknown>;

    return (
      typeof errorObject.code === 'string' &&
      typeof errorObject.message === 'string'
    );
  }

  // ============================================================
  // Gateway fallback messages
  //
  // These are ONLY for errors created by Gateway itself.
  // ============================================================

  private getDefaultMessage(code: string): string {
    switch (code) {
      case 'BAD_REQUEST':
        return 'Bad request.';

      case 'AUTH_UNAUTHORIZED':
        return 'Unauthorized.';

      case 'AUTH_FORBIDDEN':
        return 'Forbidden.';

      case 'NOT_FOUND':
        return 'The requested resource was not found.';

      case 'CONFLICT':
        return 'The requested resource conflicts with the current state.';

      case 'VALIDATION_ERROR':
        return 'Validation failed.';

      case 'SERVICE_UNAVAILABLE':
        return 'Service is currently unavailable.';

      case 'SERVICE_TIMEOUT':
        return 'The service request timed out.';

      default:
        return 'Internal server error.';
    }
  }
}
